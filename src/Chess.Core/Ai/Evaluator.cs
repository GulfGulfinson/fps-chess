    ];

    private static readonly int[] KingMiddlegame =
    [
        -30, -40, -40, -50, -50, -40, -40, -30,
        -30, -40, -40, -50, -50, -40, -40, -30,
        -30, -40, -40, -50, -50, -40, -40, -30,
        -30, -40, -40, -50, -50, -40, -40, -30,
        -20, -30, -30, -40, -40, -30, -30, -20,
        -10, -20, -20, -20, -20, -20, -20, -10,
         20,  20,   0,   0,   0,   0,  20,  20,
         20,  30,  10,   0,   0,  10,  30,  20,
    ];

    private static readonly int[] KingEndgame =
    [
        -50, -40, -30, -20, -20, -30, -40, -50,
        -30, -20, -10,   0,   0, -10, -20, -30,
        -30, -10,  20,  30,  30,  20, -10, -30,
        -30, -10,  30,  40,  40,  30, -10, -30,
        -30, -10,  30,  40,  40,  30, -10, -30,
        -30, -10,  20,  30,  30,  20, -10, -30,
        -30, -30,   0,   0,   0,   0, -30, -30,
        -50, -30, -30, -30, -30, -30, -30, -50,
    ];

    private const int EndgameMaterialThreshold = 1800;

    public static int Evaluate(Position position)
    {
        var pieces = position.Pieces().ToList();
        var officerMaterial = pieces
            .Where(p => p.Piece.Type is not (PieceType.Pawn or PieceType.King))
            .Sum(p => PieceValue(p.Piece.Type));
        var endgame = officerMaterial <= EndgameMaterialThreshold;

        var whiteScore = 0;
        foreach (var (square, piece) in pieces)
        {
            var tableIndex = piece.Color == PieceColor.White
                ? (7 - square.Rank) * 8 + square.File
                : square.Rank * 8 + square.File;
            var value = PieceValue(piece.Type) + Table(piece.Type, endgame)[tableIndex];
            whiteScore += piece.Color == PieceColor.White ? value : -value;
        }

        return position.SideToMove == PieceColor.White ? whiteScore : -whiteScore;
    }

    private static int[] Table(PieceType type, bool endgame) => type switch
    {
        PieceType.Pawn => Pawn,
        PieceType.Knight => Knight,
        PieceType.Bishop => Bishop,
        PieceType.Rook => Rook,
        PieceType.Queen => Queen,
        _ => endgame ? KingEndgame : KingMiddlegame,
    };
}
