namespace Chess.Core.Ai;

/// <summary>
/// Static evaluation: material plus piece-square tables (Tomasz Michniewski's "Simplified Evaluation Function").
/// Scores are in centipawns from the point of view of the side to move.
/// </summary>
public static class Evaluator
{
    public static int PieceValue(PieceType type) => type switch
    {
        PieceType.Pawn => 100,
        PieceType.Knight => 320,
        PieceType.Bishop => 330,
        PieceType.Rook => 500,
        PieceType.Queen => 900,
        _ => 0,
    };

    // Tables are written as seen from white with rank 8 on top, so index 0 is a8.
    private static readonly int[] Pawn =
